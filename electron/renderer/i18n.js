let currentLanguage = 'en';

function getLanguage() {
  return currentLanguage;
}

function setLanguage(language) {
  currentLanguage = language === 'zh' ? 'zh' : 'en';
  try {
    localStorage.setItem('github-repository-manager-language', currentLanguage);
  } catch (err) {
    // Language persistence is best effort.
  }
  document.documentElement.lang = currentLanguage === 'zh' ? 'zh-CN' : 'en';
  applyStaticTranslations();
}

function initLanguage() {
  let saved = 'en';
  try {
    saved = localStorage.getItem('github-repository-manager-language') || 'en';
  } catch (err) {
    saved = 'en';
  }
  currentLanguage = saved === 'zh' ? 'zh' : 'en';
  document.documentElement.lang = currentLanguage === 'zh' ? 'zh-CN' : 'en';
}

function t(key, params = {}) {
  const table = I18N[currentLanguage] || I18N.en;
  let text = table[key] !== undefined ? table[key] : (I18N.en[key] !== undefined ? I18N.en[key] : key);
  Object.entries(params).forEach(([name, value]) => {
    text = String(text).replace(new RegExp(`\\{${name}\\}`, 'g'), String(value));
  });
  return text;
}

function applyStaticTranslations() {
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-title]').forEach((element) => {
    element.title = t(element.dataset.i18nTitle);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    element.placeholder = t(element.dataset.i18nPlaceholder);
  });
}
